//! `research project tidy`: removes files that hold nothing from existing record folders.
//!
//! Scopework no longer writes per-function prerequisite views, keeps import ownership markers
//! after an import commits, or creates `data/` folders before they are used. Projects created by
//! earlier versions still carry them; this removes them, and only them.
use super::*;
use serde_json::{Value, json};

/// The first line Scopework wrote into every generated `dep.toml` and `prereq.toml`.
const VIEW_HEADER: &str = "# Managed by Scopework.";
const MARKER_PREFIX: &str = ".scopework-import-";
/// Paths listed per category in the answer; the counts are always complete.
const SAMPLE: usize = 5;

/// What one category found: entries to remove, entries kept and why.
#[derive(Default)]
struct Category {
    remove: Vec<PathBuf>,
    kept: Vec<(PathBuf, &'static str)>,
    bytes: u64,
}
impl Category {
    fn view(&self, dir: &Path) -> Value {
        let rel = |p: &Path| {
            p.strip_prefix(dir)
                .unwrap_or(p)
                .to_string_lossy()
                .replace('\\', "/")
        };
        json!({
            "remove": self.remove.len(),
            "kept": self.kept.len(),
            "bytes": self.bytes,
            "sample": self.remove.iter().take(SAMPLE).map(|p| rel(p)).collect::<Vec<_>>(),
            "kept_sample": self
                .kept
                .iter()
                .take(SAMPLE)
                .map(|(p, why)| json!({"path": rel(p), "reason": why}))
                .collect::<Vec<_>>(),
        })
    }
}

impl Library {
    /// Lists (or with `apply` removes) generated prerequisite views, import markers of jobs
    /// other than the active import, and empty `data/` folders in every record folder.
    pub fn tidy(&mut self, p: usize, apply: bool) -> Result<Value> {
        if apply && !self.writable(p) {
            return self.write_project(p, |l, p| l.tidy(p, true));
        }
        let dir = self.dir(p);
        let project = &self.projects[p];
        let index = catalog_index::Index::new(project);
        let active = project
            .active_import
            .as_ref()
            .map(|job| format!("{MARKER_PREFIX}{job}"));
        let (mut views, mut markers, mut data) = (
            Category::default(),
            Category::default(),
            Category::default(),
        );
        for node in project.nodes.iter().filter(|n| n.kind != Kind::App) {
            let Some(folder) = dir
                .join(&index.paths[&node.id])
                .parent()
                .map(Path::to_path_buf)
            else {
                continue;
            };
            let Ok(entries) = fs::read_dir(&folder) else {
                continue;
            };
            for entry in entries.flatten() {
                let name = entry.file_name().to_string_lossy().into_owned();
                let path = entry.path();
                let size = entry.metadata().map_or(0, |m| m.len());
                if name == "dep.toml" || name == "prereq.toml" {
                    let generated =
                        fs::read_to_string(&path).is_ok_and(|text| text.starts_with(VIEW_HEADER));
                    if generated {
                        views.bytes += size;
                        views.remove.push(path);
                    } else {
                        views.kept.push((path, "not generated by Scopework"));
                    }
                } else if name.starts_with(MARKER_PREFIX) && path.is_file() {
                    if active.as_deref() == Some(name.as_str()) {
                        markers.kept.push((path, "active import"));
                    } else {
                        markers.bytes += size;
                        markers.remove.push(path);
                    }
                } else if name == "data" && path.is_dir() {
                    let empty = fs::read_dir(&path).is_ok_and(|mut d| d.next().is_none());
                    if empty {
                        data.remove.push(path);
                    } else {
                        data.kept.push((path, "holds files"));
                    }
                }
            }
        }
        let mut failed = vec![];
        let mut removed = [0usize; 3];
        if apply {
            for (slot, category) in [&views, &markers].into_iter().enumerate() {
                for path in &category.remove {
                    match fs::remove_file(path) {
                        Ok(()) => removed[slot] += 1,
                        Err(e) => failed.push(format!("{}: {e}", path.display())),
                    }
                }
            }
            // `remove_dir` refuses a folder that is no longer empty, so a file written into it
            // since the scan survives.
            for path in &data.remove {
                match fs::remove_dir(path) {
                    Ok(()) => removed[2] += 1,
                    Err(e) => failed.push(format!("{}: {e}", path.display())),
                }
            }
        }
        let summary = json!({
            "project": project.id,
            "applied": apply,
            "views": views.view(&dir),
            "import_markers": markers.view(&dir),
            "data_folders": data.view(&dir),
            "removed": {"views": removed[0], "import_markers": removed[1], "data_folders": removed[2]},
            "failed": failed,
        });
        if apply && removed.iter().any(|&n| n > 0) {
            let text = format!(
                "Removed {} prerequisite views, {} import markers and {} empty data folders",
                removed[0], removed[1], removed[2]
            );
            let diff = json!({"removed": summary["removed"], "failed": failed.len()});
            self.append_history(p, "project-tidy", &text, &[], &[], Some(diff))?;
        }
        Ok(summary)
    }
}
